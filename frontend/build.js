// Generates config.js from the API_BASE_URL env var (Cloudflare Pages build step).
// Usage: API_BASE_URL=https://bbc-academy-api.onrender.com node build.js
// With no env var, config.js keeps demo mode ("").
const fs = require('fs');
const base = (process.env.API_BASE_URL || '').replace(/\/$/, '');
fs.writeFileSync('config.js', `// Generated by build.js — do not edit by hand when deploying via CI.
window.BBC_API_BASE = ${JSON.stringify(base)};
`);
console.log('config.js written, API_BASE_URL=' + (base || '(demo mode)'));
